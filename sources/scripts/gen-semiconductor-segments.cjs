#!/usr/bin/env node
/**
 * Regenerates supabase/functions/stock-report/semiconductorSegments.ts from the TPEx industry
 * value-chain site (ic.tpex.org.tw, 半導體 → introduce.php?ic=D000).
 *
 * TWSE/TPEx's official industry code has one bucket, 半導體業 (24); the split into IC 設計 / 晶圓製造 /
 * 封裝測試 only exists on that site, which has no API (HTML only). So the split is generated here,
 * reviewed in git, and committed: the Edge Function never fetches the site at runtime.
 *
 * Usage:  node scripts/gen-semiconductor-segments.cjs          (writes the file)
 *         node scripts/gen-semiconductor-segments.cjs --print  (prints a summary, writes nothing)
 */
const fs = require('node:fs')
const path = require('node:path')

const URL = 'https://ic.tpex.org.tw/introduce.php?ic=D000'
const OUT = path.join(__dirname, '..', 'supabase', 'functions', 'stock-report', 'semiconductorSegments.ts')

/**
 * Site block id → our segment. Where one ticker sits in several blocks the earlier entry wins
 * (a foundry that also lists "design services" is a foundry for money-flow purposes).
 */
const BLOCKS = [
  ['D300', 'foundry'], // IC/晶圓製造
  ['D900', 'osat'], // IC封裝測試
  ['D100', 'design'], // IC設計
  ['DC00', 'design'], // IP設計/IC設計代工服務
]

async function main() {
  const res = await fetch(URL, { headers: { 'User-Agent': 'Mozilla/5.0' } })
  if (!res.ok) throw new Error(`HTTP ${res.status} from ${URL}`)
  const html = await res.text()
  // The <noscript> copy of the page carries every company list in plain HTML.
  const ns = html.slice(html.indexOf('<noscript>'))
  const blocks = new Map()
  for (const part of ns.split(/(?=<div id="companyList_)/)) {
    const m = part.match(/^<div id="companyList_(\w+)" title="([^"]*)"/)
    if (!m) continue
    const codes = [...new Set([...part.matchAll(/company_basic\.php\?stk_code=(\w+)/g)].map((x) => x[1]))]
    blocks.set(m[1], { title: m[2], codes })
  }

  const map = {}
  const overlaps = []
  for (const [id, seg] of BLOCKS) {
    const b = blocks.get(id)
    if (!b || b.codes.length === 0) throw new Error(`block ${id} missing or empty — the page layout changed`)
    for (const code of b.codes) {
      if (map[code] && map[code] !== seg) overlaps.push(`${code}: ${map[code]} kept over ${seg}`)
      else map[code] = map[code] ?? seg
    }
  }

  // Anchors that must hold; a failure means the parse (or the site) is wrong, not that the list is stale.
  const anchors = { 2330: 'foundry', 2303: 'foundry', 2454: 'design', 2379: 'design', 3711: 'osat', 2449: 'osat' }
  for (const [code, seg] of Object.entries(anchors)) {
    if (map[code] !== seg) throw new Error(`anchor ${code} expected ${seg}, got ${map[code]}`)
  }

  const counts = {}
  for (const seg of Object.values(map)) counts[seg] = (counts[seg] ?? 0) + 1
  console.log('segments:', counts, 'overlaps resolved:', overlaps.length)
  if (process.argv.includes('--print')) return

  const sorted = Object.entries(map).sort(([a], [b]) => a.localeCompare(b))
  const body = sorted.map(([code, seg]) => `  '${code}': '${seg}',`).join('\n')
  fs.writeFileSync(
    OUT,
    `/**
 * Semiconductor sub-segment of a ticker, from the TPEx industry value-chain site.
 * GENERATED by scripts/gen-semiconductor-segments.cjs on ${new Date().toISOString().slice(0, 10)} — do not edit by hand.
 *
 * Only used for tickers whose official industry code is 24 (半導體業); a 24 ticker missing here is
 * 'other' (equipment, materials, distribution, or listed after this file was generated).
 * Precedence where the site lists a ticker in several blocks: foundry > osat > design.
 */
export type SemiconductorSegment = 'design' | 'foundry' | 'osat'

export const SEMICONDUCTOR_SEGMENTS: Readonly<Record<string, SemiconductorSegment>> = {
${body}
}
`,
  )
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${sorted.length} tickers)`)
}

main().catch((e) => {
  console.error(String(e))
  process.exit(1)
})
