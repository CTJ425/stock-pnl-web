/**
 * Identify stock category / industry badge.
 * Prioritizes quote?.industry (live official TWSE/TPEx stream).
 * If industry is not yet available, resolves via rule-based ETF / ETN / TDR / REITs / Preferred stock,
 * followed by common stock dictionary, and finally company name heuristic fallback.
 * Returns a short label (e.g. '半導體業', '債券 ETF', '特別股') or null if unknown.
 */
export function getStockCategory(
  ticker: string,
  name?: string,
  industry?: string | null,
): string | null {
  const t = ticker.trim().toUpperCase()
  if (!t) return null

  if (industry) {
    const trimmed = industry.trim()
    if (trimmed && trimmed !== '-' && trimmed !== '--') {
      return trimmed
    }
  }

  // 1. Taiwan ETF rules: all start with '00'
  if (t.startsWith('00')) {
    if (t.endsWith('B')) return '債券 ETF'
    if (t.endsWith('L')) return '槓桿 ETF'
    if (t.endsWith('R')) return '反向 ETF'
    return '股票型 ETF'
  }

  // 2. ETN: starts with '02'
  if (t.startsWith('02')) {
    return 'ETN'
  }

  // 3. TDR: starts with '91'
  if (t.startsWith('91')) {
    return 'TDR'
  }

  // 4. REITs: starts with '01'
  if (t.startsWith('01')) {
    return 'REITs'
  }

  // 5. Preferred stock: 4 digits + letter (e.g. 2881A)
  if (/^\d{4}[A-Z]$/.test(t)) {
    return '特別股'
  }

  // 6. Direct common stock dictionary lookup
  if (COMMON_STOCK_INDUSTRIES[t]) {
    return COMMON_STOCK_INDUSTRIES[t]
  }

  // 7. Secondary heuristic by company name if available
  if (name) {
    const n = name.trim()
    if (/金控|銀行|人壽|證券|期貨/.test(n)) return '金融保險'
    if (/鋼鐵/.test(n)) return '鋼鐵'
    if (/水泥/.test(n)) return '水泥'
    if (/航運|海運|航空/.test(n)) return '航運'
    if (/建設|營造|建材/.test(n)) return '建材營造'
    if (/生技|製藥|醫療|醫材|藥/.test(n)) return '生技醫療'
    if (/化學|石化/.test(n)) return '化學'
    if (/紡織|化纖/.test(n)) return '紡織纖維'
    if (/食品/.test(n)) return '食品'
    if (/汽車/.test(n)) return '汽車'
    if (/造紙|紙業/.test(n)) return '造紙'
    if (/橡膠/.test(n)) return '橡膠'
    if (/電信|網通/.test(n)) return '通信網路'
    if (/半導體|晶圓/.test(n)) return '半導體'
    if (/面板|光電/.test(n)) return '光電'
    if (/遊戲|文創/.test(n)) return '文化創意'
    if (/能源|綠能|太陽能|環保/.test(n)) return '綠能環保'
    if (/資訊|軟體/.test(n)) return '資訊服務'
    if (/雲端|電商/.test(n)) return '數位雲端'
    if (/飯店|餐飲|美食|旅行|觀光/.test(n)) return '觀光餐旅'
    if (/居家|衛浴|家具/.test(n)) return '居家生活'
    if (/美債|公司債|公債|投等債/.test(n)) return '債券 ETF'
    if (/正2|槓桿/.test(n)) return '槓桿 ETF'
    if (/反1|反向/.test(n)) return '反向 ETF'
    if (/ETF|基金/.test(n)) return '股票型 ETF'
    if (/ETN/.test(n)) return 'ETN'
    if (/DR$/.test(n)) return 'TDR'
    if (/特$/.test(n) && /[A-Z]/.test(t)) return '特別股'
  }

  return null
}
